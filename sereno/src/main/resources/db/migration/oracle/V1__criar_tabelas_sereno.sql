DECLARE
    PROCEDURE criar_tabela(p_nome IN VARCHAR2, p_ddl IN VARCHAR2) IS
        v_qtd NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_qtd FROM USER_TABLES WHERE TABLE_NAME = p_nome;
        IF v_qtd = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;

    PROCEDURE criar_indice(p_nome IN VARCHAR2, p_ddl IN VARCHAR2) IS
        v_qtd NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_qtd FROM USER_INDEXES WHERE INDEX_NAME = p_nome;
        IF v_qtd = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    criar_tabela('SER_USUARIO',
        'CREATE TABLE SER_USUARIO (
            ID              NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
            NOME            VARCHAR2(100)   NOT NULL,
            EMAIL           VARCHAR2(150)   NOT NULL,
            SENHA_HASH      VARCHAR2(100)   NOT NULL,
            ROLE            VARCHAR2(20)    NOT NULL,
            CRIADO_EM       TIMESTAMP(6)    NOT NULL,
            ATUALIZADO_EM   TIMESTAMP(6)    NOT NULL,
            CONSTRAINT PK_SER_USUARIO PRIMARY KEY (ID),
            CONSTRAINT UK_SER_USUARIO_EMAIL UNIQUE (EMAIL),
            CONSTRAINT CK_SER_USUARIO_ROLE CHECK (ROLE IN (''CIDADAO'', ''GESTOR''))
        )');

    criar_tabela('SER_LOCAL',
        'CREATE TABLE SER_LOCAL (
            ID                      NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
            NOME                    VARCHAR2(120)   NOT NULL,
            DESCRICAO               VARCHAR2(1000),
            CATEGORIA               VARCHAR2(30)    NOT NULL,
            ENDERECO                VARCHAR2(255)   NOT NULL,
            LATITUDE                NUMBER(9,6)     NOT NULL,
            LONGITUDE               NUMBER(9,6)     NOT NULL,
            RECURSOS_ACESSIBILIDADE VARCHAR2(500),
            INDICE_CALMA            NUMBER(4,2),
            TOTAL_AVALIACOES        NUMBER(10)      DEFAULT 0 NOT NULL,
            CRIADO_POR_ID           NUMBER(19),
            CRIADO_EM               TIMESTAMP(6)    NOT NULL,
            ATUALIZADO_EM           TIMESTAMP(6)    NOT NULL,
            CONSTRAINT PK_SER_LOCAL PRIMARY KEY (ID),
            CONSTRAINT FK_SER_LOCAL_CRIADO_POR FOREIGN KEY (CRIADO_POR_ID) REFERENCES SER_USUARIO (ID) ON DELETE SET NULL,
            CONSTRAINT CK_SER_LOCAL_INDICE CHECK (INDICE_CALMA BETWEEN 0 AND 10),
            CONSTRAINT CK_SER_LOCAL_LAT CHECK (LATITUDE BETWEEN -90 AND 90),
            CONSTRAINT CK_SER_LOCAL_LNG CHECK (LONGITUDE BETWEEN -180 AND 180)
        )');

    criar_tabela('SER_AVALIACAO',
        'CREATE TABLE SER_AVALIACAO (
            ID                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
            USUARIO_ID          NUMBER(19)      NOT NULL,
            LOCAL_ID            NUMBER(19)      NOT NULL,
            NIVEL_RUIDO         NUMBER(1)       NOT NULL,
            NIVEL_ILUMINACAO    NUMBER(1)       NOT NULL,
            NIVEL_LOTACAO       NUMBER(1)       NOT NULL,
            PERIODO_VISITA      VARCHAR2(10)    NOT NULL,
            COMENTARIO          VARCHAR2(500),
            CRIADO_EM           TIMESTAMP(6)    NOT NULL,
            ATUALIZADO_EM       TIMESTAMP(6)    NOT NULL,
            CONSTRAINT PK_SER_AVALIACAO PRIMARY KEY (ID),
            CONSTRAINT FK_SER_AVALIACAO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES SER_USUARIO (ID) ON DELETE CASCADE,
            CONSTRAINT FK_SER_AVALIACAO_LOCAL FOREIGN KEY (LOCAL_ID) REFERENCES SER_LOCAL (ID) ON DELETE CASCADE,
            CONSTRAINT UK_SER_AVALIACAO_USUARIO_LOCAL UNIQUE (USUARIO_ID, LOCAL_ID),
            CONSTRAINT CK_SER_AVALIACAO_RUIDO CHECK (NIVEL_RUIDO BETWEEN 1 AND 5),
            CONSTRAINT CK_SER_AVALIACAO_ILUMINACAO CHECK (NIVEL_ILUMINACAO BETWEEN 1 AND 5),
            CONSTRAINT CK_SER_AVALIACAO_LOTACAO CHECK (NIVEL_LOTACAO BETWEEN 1 AND 5),
            CONSTRAINT CK_SER_AVALIACAO_PERIODO CHECK (PERIODO_VISITA IN (''MANHA'', ''TARDE'', ''NOITE''))
        )');

    criar_indice('IX_SER_AVALIACAO_LOCAL', 'CREATE INDEX IX_SER_AVALIACAO_LOCAL ON SER_AVALIACAO (LOCAL_ID)');
    criar_indice('IX_SER_LOCAL_CATEGORIA', 'CREATE INDEX IX_SER_LOCAL_CATEGORIA ON SER_LOCAL (CATEGORIA)');
END;
